/**
 * Names every line in the repertoire trees and derives, per level, the Lichess puzzle
 * OpeningTags that count as "our openings" (SPEC §5.2).
 *
 *   node scripts/build-openings.ts
 *
 * Input:  data/repertoire-data.json, the lichess-org/chess-openings TSVs (CC0),
 *         downloaded once to .cache/openings/.
 * Output: data/openings.json
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildNameIndex, nameLine, openingTags, parseOpeningsTsv, type OpeningRow } from './lib/openings.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, '.cache', 'openings');
/**
 * Names reached in the first two plies (e.g. "King's Pawn Game" after 1.e4, "Sicilian Defense"
 * after 1.e4 c5) would pull in every sideline of that family, so only names from ply 3 on count
 * for the puzzle filter.
 */
const MIN_TAG_PLY = 3;
const TSV_URL = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master/';

interface MoveNode {
  n: number;
  next?: Record<string, MoveNode>;
}

async function loadRows(): Promise<OpeningRow[]> {
  mkdirSync(CACHE, { recursive: true });
  const rows: OpeningRow[] = [];
  for (const f of ['a', 'b', 'c', 'd', 'e']) {
    const path = join(CACHE, `${f}.tsv`);
    if (!existsSync(path)) {
      console.log(`downloading ${f}.tsv`);
      const res = await fetch(TSV_URL + `${f}.tsv`, { headers: { 'User-Agent': 'chesshabits-data-script' } });
      if (!res.ok) throw new Error(`${f}.tsv: HTTP ${res.status}`);
      writeFileSync(path, await res.text());
    }
    rows.push(...parseOpeningsTsv(readFileSync(path, 'utf8')));
  }
  return rows;
}

async function main() {
  const rows = await loadRows();
  const index = buildNameIndex(rows);
  const data = JSON.parse(readFileSync(join(ROOT, 'data', 'repertoire-data.json'), 'utf8')) as {
    trees: Record<string, { tree: Record<string, MoveNode> }>;
  };

  const lines: Record<string, string> = {};
  const perLevel: Record<string, { names: Set<string>; sides: Map<string, Set<string>> }> = {};

  for (const [key, { tree }] of Object.entries(data.trees)) {
    const [, level, color] = key.match(/^level(\d)_(white|black)$/)!;
    const bucket = (perLevel[level] ??= { names: new Set(), sides: new Map() });
    const walk = (children: Record<string, MoveNode> | undefined, line: string[]) => {
      for (const [san, node] of Object.entries(children ?? {})) {
        const next = [...line, san];
        const name = nameLine(index, next);
        if (name) {
          lines[next.join(' ')] = name;
          const tag = openingTags(name).variation;
          // Family-only names ("<Family>_Other_variations") cover every sideline of the family: too broad.
          if (next.length >= MIN_TAG_PLY && !tag.endsWith('_Other_variations')) {
            bucket.names.add(name);
            if (!bucket.sides.has(tag)) bucket.sides.set(tag, new Set());
            bucket.sides.get(tag)!.add(color);
          }
        }
        walk(node.next, next);
      }
    };
    walk(tree, []);
  }

  const out = {
    source:
      'Opening names from lichess-org/chess-openings (CC0), matched by position so transpositions count. ' +
      'Generated by scripts/build-openings.ts; do not edit by hand.',
    lines: Object.fromEntries(Object.entries(lines).sort(([a], [b]) => a.localeCompare(b))),
    levels: Object.fromEntries(
      Object.entries(perLevel).map(([level, b]) => [
        level,
        {
          names: [...b.names].sort(),
          // Variation tag -> the color(s) we play in it at this level (the puzzle solver must be one of them).
          tags: Object.fromEntries([...b.sides].sort(([a], [z]) => a.localeCompare(z)).map(([t, c]) => [t, [...c].sort()])),
        },
      ]),
    ),
  };
  writeFileSync(join(ROOT, 'data', 'openings.json'), JSON.stringify(out, null, 1) + '\n');
  console.log(`named ${Object.keys(lines).length} lines`);
  for (const [level, b] of Object.entries(out.levels)) {
    console.log(`level ${level}: ${Object.entries(b.tags).map(([t, c]) => `${t} (${c.join('/')})`).join(', ')}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
